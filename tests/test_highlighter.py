"""
Unit tests for ScriptCAD PythonHighlighter.
Verifies correct syntax tokenization, multiline docstring state transitions,
and ensures code outside of docstrings is not incorrectly formatted as strings.
"""

import os
import sys
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

try:
    from gui.qt_compat import QTextDocument, QGuiApplication
    from gui.highlighter import PythonHighlighter
except ImportError:
    QTextDocument = None
    PythonHighlighter = None
    QGuiApplication = None


class TestPythonHighlighter(unittest.TestCase):
    """Test suite for PythonHighlighter."""

    def setUp(self):
        if QTextDocument is None or PythonHighlighter is None or QGuiApplication is None:
            self.skipTest("Qt/PySide environment not available")
        if QGuiApplication.instance() is None:
            self.app = QGuiApplication(sys.argv[:1])
        else:
            self.app = QGuiApplication.instance()

    def test_multiline_docstring_state_closing(self):
        """Verify that multiline docstring correctly closes and does not leave subsequent code as string state."""
        sample_code = (
            "# SPDX-License-Identifier: LGPL-2.1-or-later\n"
            "# Auto-generated by ScriptCAD Model Decompiler\n"
            '"""\n'
            "Procedural CAD script reverse-engineered from entire 3D model:\n"
            " - Body (PartDesign::Body)\n"
            '"""\n'
            "\n"
            "from scriptcad import *\n"
            "\n"
            "# Procedural Geometry\n"
            "body = Rectangle(width=15.0, height=30.0, center=True).extrude(distance=5.0)\n"
            "body = body.fillet(radius=7.49, edge_indices=[2, 7])\n"
            'body.show("Body")\n'
        )

        doc = QTextDocument()
        doc.setPlainText(sample_code)
        hl = PythonHighlighter(doc, is_dark=True)
        hl.rehighlight()

        # Line 1 (0): comment -> state 0
        self.assertEqual(doc.findBlockByNumber(0).userState(), 0)
        # Line 2 (1): comment -> state 0
        self.assertEqual(doc.findBlockByNumber(1).userState(), 0)
        # Line 3 (2): """ opening -> state 1
        self.assertEqual(doc.findBlockByNumber(2).userState(), 1)
        # Line 4 (3): inside docstring -> state 1
        self.assertEqual(doc.findBlockByNumber(3).userState(), 1)
        # Line 5 (4): inside docstring -> state 1
        self.assertEqual(doc.findBlockByNumber(4).userState(), 1)
        # Line 6 (5): """ closing -> state 0 (MUST NOT BE 1!)
        self.assertEqual(doc.findBlockByNumber(5).userState(), 0)
        # Line 7 (6): blank -> state 0
        self.assertEqual(doc.findBlockByNumber(6).userState(), 0)
        # Line 8 (7): from scriptcad import * -> state 0
        self.assertEqual(doc.findBlockByNumber(7).userState(), 0)
        # Line 11 (10): body = Rectangle(...) -> state 0
        self.assertEqual(doc.findBlockByNumber(10).userState(), 0)

    def test_single_line_docstring(self):
        """Test docstring that opens and closes on the same line."""
        sample_code = '"""Short single-line docstring."""\nx = Box(10.0, 10.0, 10.0)\n'
        doc = QTextDocument()
        doc.setPlainText(sample_code)
        hl = PythonHighlighter(doc, is_dark=True)
        hl.rehighlight()

        self.assertEqual(doc.findBlockByNumber(0).userState(), 0)
        self.assertEqual(doc.findBlockByNumber(1).userState(), 0)


if __name__ == "__main__":
    unittest.main()
